// Action union and RulesError.

import type { HexCoord, CardType, Material, PlayerId } from './state';

export interface RulesError {
  readonly code: string;
  readonly message: string;
}

// ── M2 actions ────────────────────────────────────────────────────────────────

// Step 1a: when more than one stack is open, draw from one of them (the face-down stacks:
// you choose a stack, then see its top piece). The draw cannot be changed; PLACE_PIECE must
// then use this stack. With only one open stack there is no draw step.
export interface DrawPieceAction {
  readonly type: 'DRAW_PIECE';
  readonly stackIndex: 0 | 1 | 2;
}

// Step 1: take the top piece from a stack and place it adjacent to the board.
// Players freely choose orientation (0–5) at placement time.
export interface PlacePieceAction {
  readonly type: 'PLACE_PIECE';
  readonly stackIndex: 0 | 1 | 2;
  readonly coord: HexCoord;
  readonly rotation?: number; // 0–5; defaults to 0
}

// Step 2: provide the dice values for this turn's roll (one per mine on board).
// Dice values (1–6) are generated by the caller from state.rng; the engine
// accepts them as input to stay pure and deterministic.
export interface RollDiceAction {
  readonly type: 'ROLL_DICE';
  readonly rolls: ReadonlyArray<number>;
}

// Step 3: signal the end of the free-action window (no more belt/card/mine actions).
export interface EndActionsAction {
  readonly type: 'END_ACTIONS';
}

// Step 4: place the active player's meeple on an owned building or mine.
export interface PlaceMeepleAction {
  readonly type: 'PLACE_MEEPLE';
  readonly pieceId: string;
  readonly slotIndex?: 0 | 1; // 0=resource, 1=upgrade (mines only); omit for buildings
}

// End the turn without placing a meeple (valid when no legal meeple targets exist).
export interface EndTurnAction {
  readonly type: 'END_TURN';
}

// ── M3 actions ────────────────────────────────────────────────────────────────

// Place a belt on a board piece, linking two perimeter connection points.
// fromPoint and toPoint are indices [0, CONNECTION_POINTS_PER_PIECE[pieceType]).
// The circular distance between the two points must be > 2 (straight-through routing).
export interface PlaceBeltAction {
  readonly type: 'PLACE_BELT';
  readonly pieceId: string;
  readonly fromPoint: number;
  readonly toPoint: number;
}

// Remove an owned belt, returning it to the player's supply (beltsRemaining++).
export interface RemoveBeltAction {
  readonly type: 'REMOVE_BELT';
  readonly beltId: string;
}

// Place a teleporter on a buffer of a building you own.
// Input teleporter: feeds the building's inputs from your inventory on any turn.
// Output teleporter: diverts produced materials directly to your inventory.
export interface PlaceTeleporterAction {
  readonly type: 'PLACE_TELEPORTER';
  readonly pieceId: string;
  readonly bufferType: 'input' | 'output';
}

// ── M4 actions ────────────────────────────────────────────────────────────────

// Purchase one belt from the bank for 1 ore value-unit (adds to beltsRemaining supply).
// Placing a belt from existing supply (PLACE_BELT) is free; this buys an additional one.
export interface BuyBeltAction {
  readonly type: 'BUY_BELT';
}

// Place one of your Control Modules on a building to claim/multi-claim it.
// Cost = controlModule value in resource-units. Minimum module = mineCount (claim floor).
// A player may hold at most 3 claims on a single building.
export interface ClaimBuildingAction {
  readonly type: 'CLAIM_BUILDING';
  readonly pieceId: string;
  readonly controlModule: number;       // which module from player.controlModules to place
  readonly fromProductionIncrease?: boolean; // consumes one of the 4 PI bonus actions
  readonly fromFreeClaim?: boolean;     // free claim earned from mine slot 1 (no ore cost)
}

// Swap one of your in-play modules for a higher one.
// Paid cost = newModule - oldModule value-units.
// freeCredits (0–diff): how many freeUpgradesRemaining to consume instead of paying.
// All free credits in a round must go to the same building (tracked via freeUpgradePieceId).
export interface UpgradeBuildingAction {
  readonly type: 'UPGRADE_BUILDING';
  readonly pieceId: string;
  readonly oldModule: number;
  readonly newModule: number;
  readonly freeCredits?: number;        // defaults to 0; draws from freeUpgradesRemaining
  readonly fromProductionIncrease?: boolean; // consumes one of the 4 PI bonus actions
  readonly fromMineCredit?: boolean;    // draws diff credits from freeActionCredits (no ore)
}

// Purchase the next available mine and place it on the board immediately.
// Cost = MINE_COSTS[idx] where idx = 0 for 2nd mine, 1 for 3rd mine.
export interface BuyMineAction {
  readonly type: 'BUY_MINE';
  readonly coord: HexCoord;
  readonly rotation?: number;
}

// ── M5 actions ────────────────────────────────────────────────────────────────

// Buy one card from the top of the draw pile (no per-turn purchase limit; phase = actions).
// Play-on-draw cards resolve immediately and go to discard; others go to player's hand.
export interface BuyCardAction {
  readonly type: 'BUY_CARD';
}

// Play a card from hand (max 2 non-play-on-draw cards per turn).
// Per-card parameters are optional — only the relevant fields need be set for each card:
//   scoutingDrone  : stackIndex + pieceIndex + coord (+ rotation?)
//   shortSale      : pieceId
//   sinkHole       : pieceId
//   rdTaxWriteOff  : pieceId + bufferType
//   changingPriorities: pieceId (from) + toPieceId + controlModule
//   all others     : no extra params
export interface PlayCardAction {
  readonly type: 'PLAY_CARD';
  readonly cardType: CardType;
  readonly stackIndex?: 0 | 1 | 2;
  readonly pieceIndex?: number;
  readonly coord?: HexCoord;
  readonly rotation?: number;
  readonly pieceId?: string;
  readonly toPieceId?: string;
  readonly controlModule?: number;
  readonly bufferType?: 'input' | 'output';
}

// Place one Overstock Supplies piece (valid in actions phase when overstockPieces is non-empty).
export interface PlaceOverstockPieceAction {
  readonly type: 'PLACE_OVERSTOCK_PIECE';
  readonly coord: HexCoord;
  readonly rotation?: number;
}

// Place an auto-dropped mine (from pendingMineIds) on the board.
// Used in the placePiece phase instead of the normal PLACE_PIECE step.
// Mine occupies two hexes: primary coord and the neighbour in direction `rotation`.
export interface PlaceMineAction {
  readonly type: 'PLACE_MINE';
  readonly coord: HexCoord;
  readonly rotation?: number;
}

// Skip a factory that matched the roll this turn (instead of operating it).
// Removes it from pendingFactoryOps; the factory retains its current state.
export interface SkipFactoryRollAction {
  readonly type: 'SKIP_FACTORY_ROLL';
  readonly pieceId: string;
  // Owner acting (may be a non-active player). See OperateBuildingAction.ownerId.
  readonly ownerId?: PlayerId;
}

// Break down 1 unit of a material into lower-tier materials (see EXCHANGE_DOWN in production.ts).
// Valid in actions and roundEnd phases.
export interface ExchangeMaterialsAction {
  readonly type: 'EXCHANGE_MATERIALS';
  readonly give: Material; // break down 1 unit of this material
}

// ── Round-end building operation actions ──────────────────────────────────────

// Load one material from inventory into the first empty input slot of the building
// the active player's meeple is on. Only valid in roundEnd phase.
export interface LoadBuildingInputAction {
  readonly type: 'LOAD_BUILDING_INPUT';
  readonly pieceId: string;
  readonly material: Material;
}

// Operate a building (consume inputs, produce output). The product goes to the
// building's OUTPUT BUFFER and stays there — it is NOT auto-collected to inventory.
// (Exception: an output teleporter diverts the product straight to its owner.)
// Valid in roundEnd (meeple-based) or in actions phase when the piece is pending.
export interface OperateBuildingAction {
  readonly type: 'OPERATE_BUILDING';
  readonly pieceId: string;
  // For resolving a pending factory activation, the owner acting (may be a non-active
  // player on someone else's roll). Omitted for the round-end meeple operation (= active).
  readonly ownerId?: PlayerId;
}

// Collect material from a building's OUTPUT buffer into the active player's
// inventory (respecting the per-material cap). Only valid in roundEnd, and only
// when the player's meeple is on that building. Optional — output left uncollected
// stays in the buffer (and may flow to a connected building's input). Input
// buffers are never collected this way.
export interface CollectOutputAction {
  readonly type: 'COLLECT_OUTPUT';
  readonly pieceId: string;
}

// Undo all belts placed during the current actions phase.
// Returns those belts to the player's supply and resets the mine-belt-per-turn flag
// so the player can lay out a different belt configuration from scratch.
export interface UndoBeltsAction {
  readonly type: 'UNDO_BELTS';
}

// ── Setup ─────────────────────────────────────────────────────────────────────

// S7 interactive setup: active player claims a building (type enforced by phase).
// No resource cost; module is fixed (3 for setupClaimPF, 2 for setupClaimPP).
export interface SetupClaimAction {
  readonly type: 'SETUP_CLAIM';
  readonly pieceId: string;
}

export type Action =
  | SetupClaimAction
  | DrawPieceAction
  | PlacePieceAction
  | RollDiceAction
  | EndActionsAction
  | PlaceMeepleAction
  | EndTurnAction
  | PlaceBeltAction
  | RemoveBeltAction
  | UndoBeltsAction
  | PlaceTeleporterAction
  | ClaimBuildingAction
  | UpgradeBuildingAction
  | BuyMineAction
  | PlaceMineAction
  | BuyCardAction
  | PlayCardAction
  | PlaceOverstockPieceAction
  | BuyBeltAction
  | LoadBuildingInputAction
  | OperateBuildingAction
  | CollectOutputAction
  | SkipFactoryRollAction
  | ExchangeMaterialsAction;
